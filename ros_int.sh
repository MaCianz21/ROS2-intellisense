#!/usr/bin/env bash
# =============================================================================
# rosbuild — drop-in build + IntelliSense merge for ROS workspaces
# =============================================================================
# Copy this single file into any ROS workspace and run it.
# Zero configuration needed — detects everything automatically.
#
# Usage:
#   ./build.sh                         # build current dir or default workspace
#   ./build.sh -c                      # force build in current directory
#   ./build.sh -m                      # build only src/<user>
#   ./build.sh -m -c                   # build src/<user> in current dir
#   ./build.sh /path/to/ws             # build a specific workspace
#   ./build.sh pkg1 pkg2               # build selected packages
#   ./build.sh --no-merge              # build only, skip merge
#   ./build.sh --distro humble         # override ROS distro
# =============================================================================
set -euo pipefail

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
info()  { echo -e "\033[0;36m$*\033[0m"; }
ok()    { echo -e "\033[0;32m$*\033[0m"; }
warn()  { echo -e "\033[1;33m$*\033[0m"; }
err()   { echo -e "\033[0;31m$*\033[0m" >&2; }

# ---------------------------------------------------------------------------
# Auto-detect everything (runs every time, cached via .ros-intellisense.env)
# ---------------------------------------------------------------------------
detect_platform() {
    local os="$(uname -s)"
    local wsl=0
    if [ "$os" = "Linux" ] && [ -f /proc/version ]; then
        grep -qiE '(microsoft|wsl)' /proc/version 2>/dev/null && wsl=1
    fi
    case "$os" in
        Linux)      [ "$wsl" -eq 1 ] && echo "wsl" || echo "linux" ;;
        Darwin)     echo "macos" ;;
        MINGW*|MSYS*|CYGWIN*) echo "windows" ;;
        *)          echo "unknown" ;;
    esac
}

detect_ros_distro() {
    [ -n "${OVERRIDE_DISTRO:-}" ] && { echo "$OVERRIDE_DISTRO"; return; }
    [ -n "${ROS_DISTRO:-}" ]      && { echo "$ROS_DISTRO"; return; }
    if [ -d "/opt/ros" ]; then
        local d; d="$(ls -1 /opt/ros/ 2>/dev/null | sort -V | tail -1)"
        [ -n "$d" ] && { echo "$d"; return; }
    fi
    for f in /opt/ros/jazzy/setup.bash /opt/ros/humble/setup.bash \
             /opt/ros/iron/setup.bash /opt/ros/rolling/setup.bash; do
        [ -f "$f" ] && { basename "$(dirname "$f")"; return; }
    done
    echo "jazzy"
}

detect_compiler() {
    case "${PLATFORM:-}" in
        macos)
            for g in /opt/homebrew/bin/gcc-14 /opt/homebrew/bin/gcc-13; do
                [ -f "$g" ] && { echo "$g"; return; }
            done
            command -v gcc >/dev/null 2>&1 && { command -v gcc; return; }
            echo "/usr/bin/clang" ;;
        *)
            command -v gcc >/dev/null 2>&1 && { command -v gcc; return; }
            echo "/usr/bin/gcc" ;;
    esac
}

detect_ros_include() {
    local base="/opt/ros/$1"
    [ -d "$base/include" ] && { echo "$base/include/**"; return; }
    [ -d "$base" ]         && { echo "$base/**"; return; }
    echo ""
}

# ---------------------------------------------------------------------------
# Load or generate config (.ros-intellisense.env)
# ---------------------------------------------------------------------------
load_config() {
    local ws="$1"
    local cfg="$ws/.ros-intellisense.env"

    # If config exists, load it (allows user overrides)
    if [ -f "$cfg" ]; then
        # shellcheck disable=SC1090
        source "$cfg"
        return
    fi

    # Auto-detect and write config
    PLATFORM="$(detect_platform)"
    ROS_DISTRO="$(detect_ros_distro)"
    COMPILER_PATH="$(detect_compiler)"
    ROS_INCLUDE="$(detect_ros_include "$ROS_DISTRO")"
    MINE_BASE_PATH="src/$(whoami)"
    PARALLEL_WORKERS=4

    cat > "$cfg" <<CONF
# Auto-generated by build.sh — edit to override
ROS_DISTRO=$ROS_DISTRO
PLATFORM=$PLATFORM
COMPILER_PATH=$COMPILER_PATH
ROS_INCLUDE=$ROS_INCLUDE
PARALLEL_WORKERS=$PARALLEL_WORKERS
MINE_BASE_PATH=$MINE_BASE_PATH
CONF
}

# ---------------------------------------------------------------------------
# Ensure .vscode/ exists (auto-generate if missing)
# ---------------------------------------------------------------------------
ensure_vscode() {
    local ws="$1"
    [ -d "$ws/.vscode" ] && return 0

    mkdir -p "$ws/.vscode"

    cat > "$ws/.vscode/c_cpp_properties.json" <<CCEOF
{
  "configurations": [
    {
      "name": "ROS",
      "includePath": [
        "\${workspaceFolder}/**",
        "$ROS_INCLUDE",
        "/opt/ros/*/include/**"
      ],
      "defines": [],
      "compilerPath": "$COMPILER_PATH",
      "cStandard": "c17",
      "cppStandard": "gnu++17",
      "intelliSenseMode": "linux-gcc-x64",
      "compileCommands": "\${workspaceFolder}/build/compile_commands.json"
    }
  ],
  "version": 4
}
CCEOF

    cat > "$ws/.vscode/tasks.json" <<'TASKEOF'
{
  "version": "2.0.0",
  "tasks": [
    {
      "label": "ROS: Build & Merge IntelliSense",
      "type": "shell",
      "command": "${workspaceFolder}/build.sh",
      "args": [],
      "group": { "kind": "build", "isDefault": true },
      "problemMatcher": ["$gcc"],
      "detail": "Build all packages and merge compile_commands.json"
    },
    {
      "label": "ROS: Build (specific package) & Merge IntelliSense",
      "type": "shell",
      "command": "${workspaceFolder}/build.sh",
      "args": ["--packages-select", "${input:packageName}"],
      "group": "build",
      "problemMatcher": ["$gcc"],
      "detail": "Build a specific ROS package and merge compile_commands.json"
    },
    {
      "label": "ROS: Reset IntelliSense Database",
      "type": "shell",
      "command": "touch",
      "args": ["${workspaceFolder}/build/compile_commands.json"],
      "group": "none",
      "detail": "Touch the merged compile_commands.json to trigger C/C++ reload"
    }
  ],
  "inputs": [
    {
      "id": "packageName",
      "type": "promptString",
      "description": "ROS package name to build",
      "default": ""
    }
  ]
}
TASKEOF

    mkdir -p "$ws/build"
    touch "$ws/build/compile_commands.json"
    ok "  Generated .vscode/ configs"
}

# ---------------------------------------------------------------------------
# Parse flags
# ---------------------------------------------------------------------------
OVERRIDE_DISTRO=""
ws=""
mine=0
force_current=0
no_merge=0
packages=()

show_help() {
    cat <<EOF
rosbuild — drop-in build + IntelliSense merge

Usage:
  ./build.sh                     # build current dir (if WS) or default
  ./build.sh -c|--current        # force build in current workspace (\$PWD)
  ./build.sh -m|--mine           # build only src/<user>
  ./build.sh /path/to/ws         # build full workspace at path
  ./build.sh -m -c               # build src/<user> in current workspace
  ./build.sh [opts] pkg1 pkg2    # build selected packages

Options:
  -h, --help         Show this help
  -m, --mine         Build only packages under <workspace>/src/<user>
  -c, --current      Force build in the current directory
  --no-merge         Skip compile_commands.json merge (build only)
  --distro DISTRO    Override ROS distro (e.g. humble, rolling)

Zero config — just copy this file and run it.
EOF
    exit 0
}

while [ $# -gt 0 ]; do
    case "$1" in
        -h|--help)      show_help ;;
        -m|--mine)      mine=1; shift ;;
        -c|--current)   force_current=1; shift ;;
        --no-merge)     no_merge=1; shift ;;
        --distro)       OVERRIDE_DISTRO="$2"; shift 2 ;;
        -*)             err "Unknown option: $1"; exit 1 ;;
        *)              packages+=("$1"); shift ;;
    esac
done

# ---------------------------------------------------------------------------
# Detect workspace
# ---------------------------------------------------------------------------
detect_workspace() {
    if [ "$force_current" -eq 1 ]; then
        if [ -d "$PWD/src" ] || [ -f "$PWD/package.xml" ] || ls "$PWD"/*/package.xml >/dev/null 2>&1; then
            echo "$PWD"
            return
        fi
        err "Current directory ($PWD) is not a ROS workspace"
        exit 1
    fi

    if [ -d "$PWD/src" ]; then
        echo "$PWD"
        return
    fi

    echo "${ROSWORKSPACE:-$HOME/robotica_ws}"
}

ws="$(detect_workspace)"

if [ ! -d "$ws" ]; then
    err "Workspace not found: $ws"
    exit 1
fi

cd "$ws" || exit 1
info "Workspace: $ws"

# ---------------------------------------------------------------------------
# Load config + ensure .vscode/
# ---------------------------------------------------------------------------
load_config "$ws"
ensure_vscode "$ws"

PLATFORM="${PLATFORM:-$(detect_platform)}"
info "Platform: $PLATFORM | Distro: ${ROS_DISTRO:-jazzy} | Mine: ${MINE_BASE_PATH:-src/$(whoami)}"

# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------
common_args=(
    --symlink-install
    --parallel-workers "${PARALLEL_WORKERS:-4}"
    --cmake-args
        -DCMAKE_BUILD_TYPE=Release
        -DCMAKE_EXPORT_COMPILE_COMMANDS=ON
)

case "$PLATFORM" in
    macos) [ -d "/opt/homebrew" ] && common_args+=(-DCMAKE_PREFIX_PATH="/opt/homebrew") ;;
esac

build_success=0

if [ "$mine" -eq 1 ]; then
    mine_base="$ws/${MINE_BASE_PATH:-src/$(whoami)}"
    if [ ! -d "$mine_base" ]; then
        err "Mine base path not found: $mine_base"
        exit 1
    fi
    info "Building packages under: $mine_base"
    if [ ${#packages[@]} -eq 0 ]; then
        colcon build --base-paths "$mine_base" "${common_args[@]}" && build_success=1
    else
        colcon build --base-paths "$mine_base" "${common_args[@]}" --packages-select "${packages[@]}" && build_success=1
    fi
else
    if [ ! -d "$ws/src" ] && ls "$ws"/*/package.xml >/dev/null 2>&1; then
        info "Building packages directly in: $ws"
        if [ ${#packages[@]} -eq 0 ]; then
            colcon build --base-paths "$ws" "${common_args[@]}" && build_success=1
        else
            colcon build --base-paths "$ws" "${common_args[@]}" --packages-select "${packages[@]}" && build_success=1
        fi
    else
        info "Building workspace"
        if [ ${#packages[@]} -eq 0 ]; then
            colcon build "${common_args[@]}" && build_success=1
        else
            colcon build "${common_args[@]}" --packages-select "${packages[@]}" && build_success=1
        fi
    fi
fi

if [ "$build_success" -ne 1 ]; then
    err "Build failed!"
    exit 1
fi

ok "Build complete."

# ---------------------------------------------------------------------------
# Merge compile_commands.json
# ---------------------------------------------------------------------------
if [ "$no_merge" -eq 1 ]; then
    warn "Skipping merge (--no-merge)."
    exit 0
fi

echo ""
info "Merging compile_commands.json..."

if [ ! -d "$ws/build" ]; then
    warn "No build/ directory found — skipping merge."
    exit 0
fi

python3 -c "
import json, sys
from pathlib import Path

build = Path('$ws/build')
output = build / 'compile_commands.json'
files = sorted(build.glob('*/compile_commands.json'))
if not files:
    print('No compile_commands.json found under build/*', file=sys.stderr)
    sys.exit(1)

merged, seen = [], set()
for f in files:
    for e in json.loads(f.read_text()):
        key = (e.get('directory'), e.get('file'), e.get('command'))
        if key not in seen:
            merged.append(e)
            seen.add(key)

output.write_text(json.dumps(merged, indent=2) + '\n')
print(f'Merged {len(files)} files -> {len(merged)} entries')
"

if [ -f "$ws/build/compile_commands.json" ]; then
    touch "$ws/build/compile_commands.json"
fi

ok "IntelliSense database updated: $ws/build/compile_commands.json"
echo ""
echo -e "  \033[1;33mIf IntelliSense doesn't update:\033[0m"
echo "    Ctrl+Shift+P -> C/C++: Reset IntelliSense Database"
