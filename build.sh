#!/usr/bin/env bash
# =============================================================================
# rosbuild — one-shot build + IntelliSense merge for ROS workspaces
# =============================================================================
# Usage:
#   ./build.sh                         # Build current dir (if WS) or default
#   ./build.sh -c                      # Force build in current directory
#   ./build.sh -m                      # Build only src/user
#   ./build.sh -m -c                   # Build src/user in current dir
#   ./build.sh /path/to/ws             # Build a specific workspace
#   ./build.sh pkg1 pkg2               # Build selected packages
#   ./build.sh --no-merge              # Build only, skip merge
#
# Config is read from .ros-intellisense.env (generated by setup.sh).
# Falls back to auto-detection if config is missing.
# =============================================================================
set -euo pipefail

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
info()  { echo -e "\033[0;36m$*\033[0m"; }
ok()    { echo -e "\033[0;32m$*\033[0m"; }
warn()  { echo -e "\033[1;33m$*\033[0m"; }
err()   { echo -e "\033[0;31m$*\033[0m" >&2; }

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# ---------------------------------------------------------------------------
# Load config from .ros-intellisense.env (if present)
# ---------------------------------------------------------------------------
CONFIG_FILE="$SCRIPT_DIR/.ros-intellisense.env"

# Defaults
DEFAULT_WS="${ROSWORKSPACE:-$HOME/robotica_ws}"
MINE_BASE_PATH="src/user"
PARALLEL_WORKERS=4

# Load overrides from config file
if [ -f "$CONFIG_FILE" ]; then
    # shellcheck disable=SC1090
    source "$CONFIG_FILE"
fi

# ---------------------------------------------------------------------------
# Platform detection (for platform-specific build flags)
# ---------------------------------------------------------------------------
detect_platform() {
    local os="$(uname -s)"
    if grep -qiE '(microsoft|wsl)' /proc/version 2>/dev/null; then
        echo "wsl"
    elif [ "$os" = "Linux" ]; then
        echo "linux"
    elif [ "$os" = "Darwin" ]; then
        echo "macos"
    elif [[ "$os" =~ MINGW|MSYS|CYGWIN ]]; then
        echo "windows"
    else
        echo "unknown"
    fi
}

PLATFORM="${PLATFORM:-$(detect_platform)}"

# ---------------------------------------------------------------------------
# Help
# ---------------------------------------------------------------------------
show_help() {
    cat <<EOF
rosbuild - build a ROS workspace with IntelliSense support

Usage:
  ./build.sh                     # build current dir (if WS) or default
  ./build.sh -c|--current        # force build in current workspace (\$PWD)
  ./build.sh -m|--mine           # build only ${MINE_BASE_PATH}
  ./build.sh /path/to/ws         # build full workspace at path
  ./build.sh -m -c               # build ${MINE_BASE_PATH} in current workspace
  ./build.sh [opts] pkg1 pkg2    # build selected packages

Options:
  -h, --help       Show this help
  -m, --mine       Build only packages under <workspace>/${MINE_BASE_PATH}
  -c, --current    Force build in the current directory
  --no-merge       Skip compile_commands.json merge (build only)

Platform: ${PLATFORM}
Config:   ${CONFIG_FILE:-no config}
EOF
    exit 0
}

# ---------------------------------------------------------------------------
# Parse flags
# ---------------------------------------------------------------------------
ws=""
mine=0
force_current=0
no_merge=0
packages=()

while [ $# -gt 0 ]; do
    case "$1" in
        -h|--help)      show_help ;;
        -m|--mine)      mine=1; shift ;;
        -c|--current)   force_current=1; shift ;;
        --no-merge)     no_merge=1; shift ;;
        -*)             err "Unknown option: $1"; exit 1 ;;
        *)              packages+=("$1"); shift ;;
    esac
done

# ---------------------------------------------------------------------------
# Detect workspace
# ---------------------------------------------------------------------------
detect_workspace() {
    # 1. --current flag
    if [ "$force_current" -eq 1 ]; then
        if [ -d "$PWD/src" ] || [ -f "$PWD/package.xml" ] || ls "$PWD"/*/package.xml >/dev/null 2>&1; then
            echo "$PWD"
            return
        fi
        err "Current directory ($PWD) is not a ROS workspace"
        err "(no 'src' folder, package.xml, or packages found)"
        exit 1
    fi

    # 2. Current dir has src/
    if [ -d "$PWD/src" ]; then
        echo "$PWD"
        return
    fi

    # 3. Fallback to ROSWORKSPACE or default
    echo "$DEFAULT_WS"
}

ws="$(detect_workspace)"

if [ ! -d "$ws" ]; then
    err "Workspace not found: $ws"
    exit 1
fi

cd "$ws" || exit 1
info "Using workspace: $ws (platform: $PLATFORM)"

# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------
common_args=(
    --symlink-install
    --parallel-workers "$PARALLEL_WORKERS"
    --cmake-args
        -DCMAKE_BUILD_TYPE=Release
        -DCMAKE_EXPORT_COMPILE_COMMANDS=ON
)

# Platform-specific cmake args
case "$PLATFORM" in
    macos)
        # macOS: use Homebrew paths if available
        if [ -d "/opt/homebrew" ]; then
            common_args+=(-DCMAKE_PREFIX_PATH="/opt/homebrew")
        fi
        ;;
    wsl|linux)
        # Linux/WSL: standard paths work out of the box
        ;;
esac

build_success=0

if [ "$mine" -eq 1 ]; then
    mine_base="$ws/$MINE_BASE_PATH"
    if [ ! -d "$mine_base" ]; then
        err "Mine base path not found: $mine_base"
        exit 1
    fi
    info "Building packages under: $mine_base"
    if [ ${#packages[@]} -eq 0 ]; then
        colcon build --base-paths "$mine_base" "${common_args[@]}" && build_success=1
    else
        colcon build --base-paths "$mine_base" "${common_args[@]}" --packages-select "${packages[@]}" && build_success=1
    fi
else
    # Direct packages (no src/ folder)
    if [ ! -d "$ws/src" ] && ls "$ws"/*/package.xml >/dev/null 2>&1; then
        info "Building packages directly in: $ws"
        if [ ${#packages[@]} -eq 0 ]; then
            colcon build --base-paths "$ws" "${common_args[@]}" && build_success=1
        else
            colcon build --base-paths "$ws" "${common_args[@]}" --packages-select "${packages[@]}" && build_success=1
        fi
    else
        info "Building workspace"
        if [ ${#packages[@]} -eq 0 ]; then
            colcon build "${common_args[@]}" && build_success=1
        else
            colcon build "${common_args[@]}" --packages-select "${packages[@]}" && build_success=1
        fi
    fi
fi

if [ "$build_success" -ne 1 ]; then
    err "Build failed!"
    exit 1
fi

ok "Build complete."

# ---------------------------------------------------------------------------
# Merge compile_commands.json
# ---------------------------------------------------------------------------
if [ "$no_merge" -eq 1 ]; then
    warn "Skipping merge (--no-merge)."
    exit 0
fi

echo ""
info "Merging compile_commands.json..."

if [ ! -d "$ws/build" ]; then
    warn "No build/ directory found — skipping merge."
    exit 0
fi

# Inline Python merge — no external dependencies
python3 -c "
import json, sys
from pathlib import Path

build = Path('$ws/build')
output = build / 'compile_commands.json'
files = sorted(build.glob('*/compile_commands.json'))
if not files:
    print('No compile_commands.json found under build/*', file=sys.stderr)
    sys.exit(1)

merged, seen = [], set()
for f in files:
    for e in json.loads(f.read_text()):
        key = (e.get('directory'), e.get('file'), e.get('command'))
        if key not in seen:
            merged.append(e)
            seen.add(key)

output.write_text(json.dumps(merged, indent=2) + '\n')
print(f'Merged {len(files)} files -> {len(merged)} entries')
"

# Touch merged file to trigger VS Code C/C++ extension reload
if [ -f "$ws/build/compile_commands.json" ]; then
    touch "$ws/build/compile_commands.json"
fi

ok "IntelliSense database updated: $ws/build/compile_commands.json"
echo ""
echo -e "  \033[1;33mIf IntelliSense doesn't update:\033[0m"
echo "    Ctrl+Shift+P -> C/C++: Reset IntelliSense Database"
